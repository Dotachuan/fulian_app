export function getFulianPptSection(key) {
  return fulianPptSections.find((item) => item.key === key) || fulianPptSections[0]
}

const PPT_ASSET_VERSION = '20260923'

export function getFulianPptImagePath(slideNo) {
  const pageNumber = Number(slideNo) || 0
  const page = pageNumber < 10 ? `0${pageNumber}` : String(pageNumber)
  return `/uploads/fulian-ppt/fulian-${page}.jpg?v=${PPT_ASSET_VERSION}`
}
